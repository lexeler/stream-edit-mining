"""
Монтаж целиком языковой моделью: один запрос, весь стрим, готовый список кусков.

Никакого бустинга, никаких правил сборки с моей стороны: модель сама решает,
где начать, где закончить, что вырезать и какой длины будет выпуск. Ей даётся
всё, что мы знаем о работе монтажёра, и вся расшифровка целиком (влезает:
30–70 тыс. токенов при контексте в миллион).

  solo.py --slot 7 --tag solo1 --reasoning

Ответ — строки «начало-конец» в номерах реплик. Из них собираются таймкоды
и считается точность против настоящего монтажа.
"""
