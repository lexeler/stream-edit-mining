USER = """Расшифровка стрима: {n} реплик, эфир {mins} минут.

{text}

Выдай список кусков для выпуска."""


def parse_ranges(txt, n):
    out = []
    for m in re.finditer(r"^\s*\[?(\d+)\s*[-–—]\s*(\d+)\]?\s*$", txt, re.M):
        a, b = int(m.group(1)), int(m.group(2))
        if 1 <= a <= b <= n:
            out.append((a, b))
    if not out:                      # запасной разбор, если формат поехал
        for m in re.finditer(r"(\d+)\s*[-–—]\s*(\d+)", txt):
            a, b = int(m.group(1)), int(m.group(2))
            if 1 <= a <= b <= n:
                out.append((a, b))
    out.sort()
    merged = []
    for a, b in out:
        if merged and a <= merged[-1][1]:
            merged[-1][1] = max(merged[-1][1], b)
        else:
            merged.append([a, b])
    return merged


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--slot", required=True)
    ap.add_argument("--tag", default="solo")
    ap.add_argument("--model", default=MODEL)
    ap.add_argument("--temp", type=float, default=0.3)
    ap.add_argument("--reasoning", action="store_true")
    ap.add_argument("--maxtok", type=int, default=60000)
    ap.add_argument("--system", default="", help="файл со своим промптом")
    a = ap.parse_args()

    blocks = json.load(open(f"{DATA}/s{a.slot}.blocks.json"))["blocks"]
    lines, mapping = render_lines(blocks, with_audio=True)
    text = "\n".join(s for _, s in lines)
    N = len(mapping)
    T = blocks[-1]["end"]
    system = open(a.system).read() if a.system else SYSTEM

    t0 = time.time()
    txt, u = call(a.model, system,
                  USER.format(n=N, mins=int(T / 60), text=text),
                  temperature=a.temp, max_tokens=a.maxtok,
                  reasoning=a.reasoning)
    rng = parse_ranges(txt, N)

    dur = np.array([b["dur"] for b in blocks])
    y = np.array([b["used_frac"] for b in blocks])
    sel = np.zeros(len(blocks), bool)
    segs = []
    for lo, hi in rng:
        i0, i1 = mapping[lo], mapping[hi]
        sel[i0:i1 + 1] = True
        segs.append([float(blocks[i0]["start"]), float(blocks[i1]["end"])])
    m = []
    for s, e in segs:
        if m and s - m[-1][1] < 0.05:
            m[-1][1] = e
        else:
            m.append([s, e])
    ov = float((dur * y)[sel].sum())
    pred = float(dur[sel].sum())
    true = float((dur * y).sum())
    L = np.array([e - s for s, e in m]) if m else np.array([0.0])
    cost = (u.get("prompt_tokens", 0) * 0.07
            + u.get("completion_tokens", 0) * 0.13) / 1e6

    os.makedirs(f"{DATA}/solo", exist_ok=True)
    json.dump({"slot": a.slot, "model": a.model, "reasoning": a.reasoning,
               "ranges": rng, "segments": [[round(s, 2), round(e, 2)] for s, e in m],
               "raw": txt[-20000:], "usage": u, "cost_usd": round(cost, 4)},
              open(f"{DATA}/solo/s{a.slot}_{a.tag}.json", "w"), ensure_ascii=False)

    print(f"{a.model}{' + рассуждение' if a.reasoning else ''}: "
          f"{time.time()-t0:.0f} с, вход {u.get('prompt_tokens')} / "
          f"выход {u.get('completion_tokens')}, ${cost:.4f}")
    print(f"кусков {len(m)}, выпуск {pred/60:.1f} мин ({pred/dur.sum():.1%}), "
          f"медиана {np.median(L):.1f} с, макс {L.max():.0f} с")
    print(f"у монтажёра {true/60:.1f} мин, кусков "
          f"{len(json.load(open(f'$SEM_STREAMS/{a.slot}/narezki/timecodes.json'))['segments'])}")
    print(f"ТОЧНОСТЬ {ov/pred if pred else 0:.3f}  полнота {ov/true:.3f}  "
          f"случайно {true/dur.sum():.3f}")


if __name__ == "__main__":
    main()
