#!/usr/bin/env python3
"""
Точка открытия выпуска: с чего начинается видео.

Требование заказчика: выпуск обязан открываться приветствием — обращением
к зрителям или к людям в кадре. Словарём это не решается: «здорово» бывает
и приветствием, и оценкой («это здорово»), а «пацаны» — и обращением,
и просто словом. Языковая модель различает их надёжно, и задача ей ровно
по силам: найти одну точку в первых минутах.

Заодно она отмечает, где кончается завязка (приветствие + кто в кадре +
план дня), чтобы сборка не обрывала её на полуслове.

  ./startpoint.py --slot 2
"""
import json, os, re, time, argparse, urllib.request

KEY = os.environ.get("OPENROUTER_API_KEY", "")
URL = "https://openrouter.ai/api/v1/chat/completions"
DATA = os.environ.get("SEM_BLOCKS", "work/blocks")
OUT = DATA + "/startpoint"
WINDOW = 300.0

SYSTEM = """Ты помогаешь собрать выпуск для YouTube из записи стрима.

Канал — уличные IRL-стримы: ведущий с друзьями гуляет по
городу и устраивает всякие затеи. Стрим включается задолго до того, как
начинается собственно контент: сначала идёт техническая возня — проверяют,
пошла ли трансляция, видно ли картинку, слышно ли звук, переговариваются
с оператором.

ЗАДАЧА. Тебе дают начало эфира, разложенное на элементы с таймкодами.
Найди элемент, С КОТОРОГО ДОЛЖЕН НАЧИНАТЬСЯ ВЫПУСК.

Правильная точка старта — это первое ОБРАЩЕНИЕ: ведущий здоровается со
зрителями («здорово, пацаны», «приветствую», «всем привет», «салам»),
или здоровается с человеком, который подошёл в кадре («здорово, мужики»,
«здравствуйте»), или впервые обращается к зрителям по существу («сегодня
у нас...», «мы сейчас поедем...»).

Чего точкой старта БЫТЬ НЕ МОЖЕТ:
- техническая проверка («меня видно?», «слышно нормально?», «стрим пошёл?»);
- разговоры с оператором и между собой до того, как ведущий обратился
  к зрителям;
- слово «здорово» в значении «классно, хорошо» — это не приветствие;
- слово «пацаны», «мужики», «ребята» внутри рассказа, а не как обращение.

Ещё укажи, каким элементом заканчивается ЗАВЯЗКА — вступление, где ведущий
поздоровался, сказал, кто сегодня с ним и что они собираются делать. Обычно
это 20–60 секунд после старта. Если ничего похожего нет, укажи элемент
через 20–30 секунд после старта.

ВАЖНО. В элементе, который ты выберешь стартом, ДОЛЖНО ЗВУЧАТЬ САМО
ПРИВЕТСТВИЕ ИЛИ ОБРАЩЕНИЕ. Ты обязан процитировать его дословно из текста
этого элемента. Если в первых минутах ведущий вообще ни с кем не здоровается
и к зрителям не обращается, так и напиши: цитата "нет".

Проверь себя перед ответом: цитата должна быть именно приветствием или
обращением, а не словом «здорово» в значении «классно» и не словом
«пацаны» внутри рассказа.

ОТВЕТ. Верни только JSON без пояснений:
{"старт": НОМЕР, "цитата": "дословно из текста элемента",
 "конец_завязки": НОМЕР, "почему": "одна короткая фраза"}"""


def call(model, user, retries=3):
    payload = {"model": model,
               "messages": [{"role": "system", "content": SYSTEM},
                            {"role": "user", "content": user}],
               "temperature": 0.0, "max_tokens": 8000,
               "reasoning": {"effort": "high"}}
    for k in range(retries):
        try:
            req = urllib.request.Request(
                URL, data=json.dumps(payload).encode(),
                headers={"Authorization": f"Bearer {KEY}",
                         "Content-Type": "application/json"})
            r = json.load(urllib.request.urlopen(req, timeout=300))
            return r["choices"][0]["message"]["content"] or ""
        except Exception as e:
            if k == retries - 1:
                print(f"  ошибка: {e}")
                return ""
            time.sleep(3 * (k + 1))
    return ""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--slot", required=True)
    ap.add_argument("--model", default="google/gemini-3.7-flash")
    a = ap.parse_args()
    B = json.load(open(f"{DATA}/s{a.slot}.blocks.json"))["blocks"]
    cur = [b for b in B if b["start"] < WINDOW]
    lines = []
    for b in cur:
        t = f"{int(b['start'])//60}:{int(b['start'])%60:02d}"
        if b["kind"] == "speech":
            lines.append(f"#{b['i']} {t} реч {b['dur']:.1f}с {b['text']}")
        else:
            lines.append(f"#{b['i']} {t} пауза {b['dur']:.1f}с")
    txt = call(a.model, "Начало эфира:\n\n" + "\n".join(lines))
    m = re.search(r"\{.*?\}", txt, re.S)
    if not m:
        print("не удалось разобрать ответ:", txt[:200]); return
    d = json.loads(m.group(0))
    st = int(d["старт"]); en = int(d.get("конец_завязки", st))
    bs = {b["i"]: b for b in cur}
    os.makedirs(OUT, exist_ok=True)
    json.dump(d, open(f"{OUT}/s{a.slot}.json", "w"), ensure_ascii=False)
    b = bs.get(st)
    if b:
        t = int(b["start"])
        q = str(d.get("цитата", "")).strip()
        ok = q and q.lower() != "нет" and q.lower()[:20] in b["text"].lower()
        print(f"слот {a.slot}: старт #{st} в {t//60}:{t%60:02d}")
        print(f"  цитата: «{q}» {'(есть в тексте)' if ok else '(НЕ НАЙДЕНА в тексте!)'}")
        print(f"  реплика: {b['text'][:100]}")
        print(f"  завязка до #{en} | монтажёр взял этот блок: "
              f"{'да' if b['used_frac'] > 0.5 else 'нет'}")


if __name__ == "__main__":
    main()
