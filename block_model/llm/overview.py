#!/usr/bin/env python3
"""
Обзор стрима: модель читает весь эфир целиком и составляет карту.

Зачем. Разбор слота 1 показал: главный признак — двигает ли кусок сегодняшнюю
затею. Оценивая кусок в 15 минут, модель не знает ни затеи, ни того, что
похожая сцена уже была час назад. Значит сначала — один проход по всему
стриму (он влезает: 30–70 тыс. токенов при контексте в миллион), потом
карта кладётся в контекст при оценке реплик.

  overview.py --slot 7
Кладёт data/over/s<N>.md
"""
import json, os, sys, argparse
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))  # модули родительской папки
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ask import call, render_lines, DATA, MODEL

PROMPT = """Ниже полная расшифровка уличного стрима блогера. Стрим идёт несколько часов, монтажёр потом делает из него
выпуск для YouTube примерно на час.

Прочитай стрим целиком и составь карту — она нужна монтажёру, чтобы решать,
что оставить.

1. ЗАТЕЯ. Есть ли у стрима объявленная цель, ради которой он снят
   (челлендж, поездка, спор, задание)? Если есть — сформулируй в одну фразу
   и укажи, где она объявлена. Если стрим бесцельная прогулка — так и скажи.

2. КАРТА СЦЕН. По порядку, каждая строка:
   «время — что происходит — участники — чем закончилось».
   Сцена это смена места, занятия или собеседника. Ожидаю 15–40 сцен.

3. ПОВТОРЫ. Что в этом стриме происходит по несколько раз (подходы фанатов,
   одинаковые приветствия, возвращение к той же теме разговора). Укажи время
   каждого повторения.

4. ПУСТЫЕ ЗОНЫ. Длинные куски, где ничего не происходит: дорога без событий,
   ожидание, разговоры ни о чём. Время начала и конца каждого.

5. ВЕРШИНЫ. Пять–десять самых сильных мест эфира: где смешно, неожиданно,
   где событие. С временем.

6. НАСЫЩЕННОСТЬ. Насколько этот эфир богат материалом: густо (почти всё
   время что-то происходит), средне, или пусто (события редкие). Одна фраза
   с обоснованием.

Пиши по-русски, сжато, без вступлений.

РАСШИФРОВКА:

{text}"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--slot", required=True)
    ap.add_argument("--model", default=MODEL)
    a = ap.parse_args()
    blocks = json.load(open(f"{DATA}/s{a.slot}.blocks.json"))["blocks"]
    lines, mapping = render_lines(blocks, with_audio=True)
    text = "\n".join(s for _, s in lines)
    print(f"слот {a.slot}: {len(text)} символов (~{len(text)//3000} тыс. токенов)")
    txt, u = call(a.model, "Ты внимательный редактор видео.",
                  PROMPT.format(text=text), max_tokens=16000, reasoning=False)
    os.makedirs(f"{DATA}/over", exist_ok=True)
    p = f"{DATA}/over/s{a.slot}.md"
    open(p, "w").write(txt)
    cost = u.get("prompt_tokens", 0) / 1e6 * 0.07 + u.get("completion_tokens", 0) / 1e6 * 0.13
    print(f"вход {u.get('prompt_tokens')} / выход {u.get('completion_tokens')} "
          f"токенов, ${cost:.4f} -> {p}")


if __name__ == "__main__":
    main()
